#!/usr/bin/env python3
"""Write per-step ODoQ timings as LaTeX macros for the call-flow figure.

  tools/timing_macros.py results/stage2_main_<stamp> [--netem rtt50]

Reads breakdown.csv and summary.csv (from analyze.py) for ODoQ with a
persistent proxy connection, warm client connection, cache hit, no padding,
and writes <dir>/figures/odoq_timing_values.tex with \\newcommand lines.
Copy that file into the paper's images/ folder; main.tex \\input's it.

All values are medians in ms. Network steps run from the sender's timestamp
just before transmit() to the receiver holding the full message, so they
include QUIC processing at both ends, not only the emulated link delay.
"""

import argparse
import csv
from pathlib import Path

STEPS = [  # macro name, breakdown column(s) summed, description
    ("tBuild", ["c_build"], "client builds and encrypts the query"),
    ("tCP", ["net_c_to_p"], "client to proxy"),
    ("tSplit", ["p_split"], "proxy strips routing metadata"),
    ("tPR", ["net_p_to_r"], "proxy to resolver"),
    ("tOpen", ["r_open"], "resolver decrypts key and query"),
    ("tResolve", ["r_backend"], "Unbound lookup"),
    ("tSeal", ["r_seal", "r_send"], "resolver encrypts and sends response"),
    ("tRP", ["net_r_to_p"], "resolver to proxy"),
    ("tRelay", ["p_relay"], "proxy relays response"),
    ("tPC", ["net_p_to_c"], "proxy to client"),
    ("tDecrypt", ["c_open"], "client decrypts and verifies"),
]


def pick(rows, netem):
    for r in rows:
        if (r["variant"] == "odoq-persistent" and r["conn_mode"] == "warm"
                and r["cache"] == "hit" and r["netem"] == netem
                and r["padding"] == "none"):
            return r
    raise SystemExit(f"no odoq-persistent warm/hit/{netem}/none row found")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("campaign_dir", type=Path)
    ap.add_argument("--netem", default="rtt50")
    a = ap.parse_args()
    d = a.campaign_dir
    b = pick(list(csv.DictReader(open(d / "breakdown.csv"))), a.netem)
    s = pick(list(csv.DictReader(open(d / "summary.csv"))), a.netem)
    lines = [f"% generated by tools/timing_macros.py from {d.name}, {a.netem}",
             "% ODoQ, persistent proxy connection, warm, cache hit, no padding; medians in ms"]
    for name, cols, desc in STEPS:
        vals = [float(b[c + "_median_ms"]) for c in cols if b.get(c + "_median_ms")]
        v = sum(vals) if vals else 0.0
        lines.append(f"\\newcommand{{\\{name}}}{{{v:.2f}}} % {desc}")
    lines.append(f"\\newcommand{{\\tTotal}}{{{float(s['median_ms']):.2f}}} % end-to-end median")
    out = d / "figures" / "odoq_timing_values.tex"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
